namespace Dal;
using DalTest;
using DalApi;
using DO;

public static class Initialization
{
    private static IDal? s_dal;

    private static readonly Random s_rand = new();

    public static void Do(IDal dal)
    {
        s_dal = dal ?? throw new NullReferenceException("DAL object can not be null!");

        Console.WriteLine("Reset Configuration values and List values...");
        s_dal.ResetDB();

        Console.WriteLine("Initializing Students list ...");
        CreateOrder();
        CreateCourier();
        CreateDelivery();
    }

    private static void CreateOrder(int count = 50)
    {
        if (s_dal is null) return;
        
        for (var i = 0; i < count; i++)
        {
            var (address, lat, lon, _, _) = Mock.Addresses[i % Mock.Addresses.Length];

            var status = i switch
            {
                < 20 => OrderStatus.Open,
                < 30 => OrderStatus.InProgress,
                _ => OrderStatus.Closed
            };
            
            var randomMinutes = s_rand.Next(0, 7 * 24 * 60); // 0 to 10079 minutes (last 7 days)
            var randomSeconds = s_rand.Next(0, 60); // 0 to 59 seconds
            var randomPastTime = s_dal.Config.Clock.AddMinutes(-randomMinutes).AddSeconds(-randomSeconds);

            s_dal.Order?.Create(new Order(
                0,
                (OrderType)s_rand.Next(Enum.GetValues(typeof(OrderType)).Length),
                $"Order number {i} - autogenerated",
                address,
                Mock.CustomerName[i],
                $"050-{s_rand.Next(1000000, 9999999)}",
                s_rand.NextDouble() > 0.5,
                randomPastTime,
                status,
                lat,
                lon
            ));
        }
    }

    private static void CreateCourier(int count = 20)
    {
        if (s_dal == null) return;
        
        for (var i = 0; i < count; i++)
        {
            int id;
            do
            {
                id = s_rand.Next(10000000, 99999999);
            } while (s_dal.Courier?.Read(c => c.Id == id) != null);

            var name = Mock.CourierNames[i % Mock.CourierNames.Length];
            var email = $"{name.Replace(" ", ".").ToLower()}@gmail.com";
            var phone = $"052-{s_rand.Next(1000000, 9999999)}";

            var shipmentType = (ShipmentType)s_rand.Next(Enum.GetValues(typeof(ShipmentType)).Length);

            var isActive = s_rand.NextDouble() > 0.25;

            var startDate = s_dal.Config.Clock.AddDays(-s_rand.Next(30, 5 * 365));

            double? maxDistance = shipmentType switch
            {
                ShipmentType.Walk => s_rand.Next(1, 6),
                ShipmentType.Bicycle => s_rand.Next(3, 16),
                ShipmentType.Motorcycle => s_rand.Next(10, 41),
                ShipmentType.Car => s_rand.Next(30, 101),
                _ => null
            };

            if (s_rand.NextDouble() < 0.1)
                maxDistance = null;

            s_dal.Courier?.Create(new Courier(
                id,
                name,
                phone,
                email,
                "1234",
                isActive,
                ShipmentType: shipmentType,
                StartingWork: startDate,
                MaximumDistance: maxDistance
            ));
        }
    }

    private static void CreateDelivery(int count = 15)
    {
        if (s_dal is null) return;
        
        var orders = s_dal.Order.ReadAll()?.ToList() ?? [];
        var couriers = s_dal.Courier?.ReadAll()?.ToList() ?? [];
        if (orders.Count == 0 || couriers.Count == 0) return;

        var courierDeliveries = new Dictionary<int, List<(DateTime start, DateTime? end)>>();

        for (var i = 0; i < count && orders.Count != 0; i++)
        {
            var order = orders[s_rand.Next(orders.Count)];

            var possibleCouriers = couriers
                .Where(c => c.IsActive && (c.MaximumDistance == null || c.MaximumDistance >= s_rand.Next(1, 60)))
                .ToList();

            if (possibleCouriers.Count == 0)
                continue;

            var courier = possibleCouriers[s_rand.Next(possibleCouriers.Count)];

            var startTime = order.CreatedAt.AddMinutes(s_rand.Next(5, 120));

            if (!courierDeliveries.ContainsKey(courier.Id))
                courierDeliveries[courier.Id] = new List<(DateTime, DateTime?)>();

            bool hasConflict;
            var attempts = 0;
            do
            {
                hasConflict = courierDeliveries[courier.Id]
                    .Any(d => !(startTime.AddHours(1) < d.start || (d.end ?? d.start.AddHours(1)) < startTime));
                if (hasConflict)
                    startTime = startTime.AddMinutes(s_rand.Next(30, 180));
            } while (hasConflict && attempts++ < 5);

            var isFinished = s_rand.NextDouble() < 0.7;
            DateTime? endTime = isFinished ? startTime.AddMinutes(s_rand.Next(10, 120)) : null;

            DeliveryEndType? endType = null;
            if (isFinished)
            {
                var roll = s_rand.NextDouble();
                endType = roll switch
                {
                    < 0.65 => DeliveryEndType.Supplied,
                    < 0.75 => DeliveryEndType.RefusedByCustomer,
                    < 0.85 => DeliveryEndType.Cancelled,
                    < 0.95 => DeliveryEndType.CustomerNotFound,
                    _ => DeliveryEndType.Failed
                };
            }

            var (_, _, _, actualDistance, shipmentType) = Mock.Addresses.FirstOrDefault(a =>
                a.Address == order.Address &&
                a.Latitude == order.Latitude &&
                a.Longitude == order.Longitude);

            s_dal.Delivery?.Create(new Delivery(
                0,
                order.Id,
                courier.Id,
                shipmentType,
                startTime,
                EndTime: endTime,
                ActualDistance: actualDistance,
                DeliveryEndType: endType
            ));

            // רושמים את טווח הזמנים של השליח לשמירה על אי־חפיפה
            courierDeliveries[courier.Id].Add((startTime, endTime));

            // אם המשלוח פתוח או סגור בהצלחה – נוריד את ההזמנה מהרשימה
            if (!isFinished || endType == DeliveryEndType.Supplied)
                orders.Remove(order);

            // אם "נפתח מחדש" – ניצור שוב את אותה הזמנה אחר כך (5% מהסיכוי)
            if (isFinished && s_rand.NextDouble() < 0.05)
                orders.Add(order);
        }
    }
}